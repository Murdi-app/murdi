// من يبدأ مشروعاً جديداً لا منشأة عنده تُقيَّم أصلاً، ومن لا قوائم له يعرف
// ذلك، والحوكمة مطلبٌ نظامي أو مطلب مستثمر، والتقييم العادل منتجٌ قائم
// بذاته. فهذه تُطلب مباشرة — والباقي يبقى خلف التشخيص.
