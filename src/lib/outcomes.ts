// نتيجة المكالمة — مفردةٌ واحدة تعرفها الشاشة والخادم والقاعدة معاً.
//
// ★ كانت ثلاث مفردات في ثلاثة أماكن، ولم يكن أحد يعلم:
//   · شاشة الفرص الساخنة تعرض: أرسلتُ رسالة · ردّ — مهتم · ردّ — غير مهتم ·
//     لم يرد · طلب معاودة · رقم/بريد خاطئ · تحوّل عميلاً
//   · ومسارها في الخادم يقبل: لم يرد · مهتم · طلب معاودة · غير مهتم ·
//     رقم خاطئ · تحوّل عميلاً — فثلاثٌ من سبعٍ تُردّ بـ«نتيجة غير معروفة»
//   · وقيد القاعدة `mini_outcome_chk` يقبل: لا يرد · مهتم · طلب معاودة ·
//     غير مؤهل الآن · تحوّل عميلاً · رفض — و«لم يرد» ليست منها
//
//   والنتيجة المختارة افتراضياً كانت «لم يرد»: تمرّ من الخادم ويرفضها القيد.
//   فكانت الموظفة تُنهي المكالمة وتضغط فيقع عليها خطأ قاعدة بيانات بالإنجليزية،
//   ولا تُسجَّل النتيجة — وقد سُجِّلت اللمسة قبلها، فيفترق الجدولان.
//
//   فصار التعريف هنا وحده: من أراد نتيجةً جديدة يضيفها في هذا الملف، فتظهر
//   في الشاشتين ويقبلها الخادم — ويبقى قيد القاعدة مطابقاً لهذه القائمة.

export const OUTCOMES = [
  'أرسلتُ رسالة',
  'لم يرد',
  'مهتم',
  'طلب معاودة',
  'غير مهتم',
  'غير مؤهل الآن',
  'رقم خاطئ',
  'تحوّل عميلاً',
  // ★ ٢٩ سبتمبر: من طلب ألا نتواصل معه لا يُتصل به ثانيةً — في الترسيات تصير المنشأة «لا تتواصل»
  'طلب عدم التواصل',
] as const;

export type Outcome = (typeof OUTCOMES)[number];

export const isOutcome = (v: unknown): v is Outcome =>
  (OUTCOMES as readonly string[]).includes(String(v ?? ''));

/**
 * ما يُغلق الفرصة فلا تعود إلى صفّ اليوم ولا إلى «متابعاتي».
 *
 * ★ ٥ أكتوبر (المالك): «غير مؤهل الآن» صارت تُغلق (كانت تعود)، و«لم يرد ٣ مرات»
 *   تُكتب آلياً بعد ثالث «لم يرد» متتالية. والدفع يُغلق أيضاً — يُقرأ من المدفوعات.
 */
export const CLOSING_OUTCOMES: readonly string[] = ['غير مهتم', 'غير مؤهل الآن', 'رقم خاطئ', 'تحوّل عميلاً', 'طلب عدم التواصل', 'لم يرد ٣ مرات'];

/** ما يُبقي العميل في «متابعاتي» حتى نتيجةٍ مُغلِقة أو دفع */
export const FOLLOW_OUTCOMES: readonly string[] = ['مهتم', 'طلب معاودة', 'لم يرد', 'أرسلتُ رسالة'];
export const NO_ANSWER_LIMIT = 3;
export const NO_ANSWER_CLOSED = 'لم يرد ٣ مرات';

/** يوم العمل التالي بتوقيت الرياض (الأحد–الخميس) — موعد معاودة «لم يرد» */
export function nextWorkday(from = new Date()): string {
  const d = new Date(from.getTime() + 3 * 3600_000);
  do { d.setUTCDate(d.getUTCDate() + 1); } while (d.getUTCDay() === 5 || d.getUTCDay() === 6);
  return d.toISOString().slice(0, 10);
}
export const closesOpportunity = (v: string | null | undefined): boolean =>
  !!v && CLOSING_OUTCOMES.includes(v);

/**
 * مرادفاتٌ قديمة بقيت في صفوفٍ كُتبت قبل التوحيد — تُقرأ ولا تُكتب.
 * والهجرة حوّلت المخزون، وهذه شبكةُ أمانٍ لما قد يُفلت.
 */
const LEGACY: Record<string, Outcome> = {
  'لا يرد': 'لم يرد',
  'رفض': 'غير مهتم',
  'ردّ — مهتم': 'مهتم',
  'ردّ — غير مهتم': 'غير مهتم',
  'رقم/بريد خاطئ': 'رقم خاطئ',
};

/** يُرجع النتيجة المعتمدة، أو null إن لم تكن معروفة أصلاً. */
export const canonicalOutcome = (v: string | null | undefined): Outcome | null => {
  const s = String(v ?? '').trim();
  if (!s) return null;
  if (isOutcome(s)) return s;
  return LEGACY[s] ?? null;
};
