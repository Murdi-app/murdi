// ما لا تراه الموظفة.
//
// ★ سرّ العمل ليس الأسعار المعلنة على الموقع — هي معلنة. السرّ **نسبة أتعاب
//   النجاح، وما حُصِّل فعلاً، وما بقي في الذمة**. وهذه ثلاثة أرقام تعرف بها
//   الموظفةُ ما يدخل جيب المكتب من كل عميل، وتُقاس بها في نفسها، وتُحمل معها
//   إن انتقلت إلى منافس. وقد كانت تخرج فعلاً: `/admin/deal` يُرجع
//   `contracts.fee_percent` و`fixed_amount`، وخطُّ الصفقة فيه «صدر العقد —
//   أتعاب ٦٪» و«دفعة محصّلة — 7900 ريال».
//
// ★ والثاني: **رقم مالك العميل**. خطّ الصفقة يحمل ملاحظاتٍ كُتبت فيها أرقام
//   ملّاك — منها ملاحظةٌ عن تسريبٍ وقع أصلاً، فيها الرقم نفسه. وهو الرقم
//   الذي لا يخرج إلى جهة، فلا يُعرض على شاشةٍ يُنسخ منها.
//
// ★ والقاعدة: يُنقّى في **الخادم** قبل أن يُرسل — لا يُخفى في المتصفّح.
//   ما وصل الجهازَ وُصل إليه.

// أنماط المال: نسبة أتعاب · مبلغ محصّل · تسعيرة خدمة · وأي مبلغ بالريال.
// و«ريال» وحدها كافية: «7900 ريال — خدمة» لا تحمل كلمةً دالّة أخرى، وكانت
// تمرّ لأن الكلمة الدالّة («دفعة محصّلة») في عنوان الصفّ لا في تفصيله.
const MONEY_LINE = /(أتعاب|عمولة|نسبة|محصّل|محصل|دفعة|سُعِّرت|سعرت|رسوم|ريال|﷼|٪|%)/;

/** رقم جوال سعودي في نصٍّ حر */
const PHONE_RE = /(?:\+?\s*9\s*6\s*6|0)(?:[\s\-.()]*\d){8,10}/g;

/** يُخفي أرقام الجوال ويُبقي النصّ مقروءاً */
export const hidePhones = (s: string): string =>
  String(s || '').replace(PHONE_RE, '•••••••');

/**
 * يُخفي كل رقمٍ ماليّ في سطرٍ يتحدث عن مال.
 * و`ctx` سياق الصفّ كله — لأن الكلمة الدالّة قد تكون في العنوان والرقم في
 * التفصيل، فيُقرآن معاً أو يمرّ المبلغ.
 */
export const hideMoney = (s: string, ctx?: string): string => {
  const t = String(s || '');
  if (!MONEY_LINE.test(t + ' ' + String(ctx || ''))) return t;
  return t.replace(/[\d٠-٩][\d٠-٩,٬.]*\s*(?:٪|%|ريال|﷼)?/g, '•••');
};

export type TimelineRow = {
  kind?: string | null;
  title?: string | null;
  detail?: string | null;
  [k: string]: unknown;
};

/**
 * خطّ الصفقة كما تراه الموظفة: الأحداث كلها تبقى — فهي تحتاج أن تعرف أن
 * العقد صدر وأن الدفعة وصلت — والأرقام وحدها تُطمس. فتعرف **ما وقع** ولا
 * تعرف **بكم**.
 */
export function redactTimeline<T extends TimelineRow>(rows: T[]): T[] {
  return (rows || []).map((r) => {
    const ctx = String(r.title || '') + ' ' + String(r.detail || '');
    return {
      ...r,
      title: hidePhones(hideMoney(String(r.title || ''), ctx)),
      detail: hidePhones(hideMoney(String(r.detail || ''), ctx)),
    };
  });
}

/** العقد كما تراه الموظفة: حالته وتاريخ توقيعه — بلا نسبة ولا مبلغ */
export function redactContract(c: Record<string, unknown> | null): Record<string, unknown> | null {
  if (!c) return null;
  return { status: c.status ?? null, signed_at: c.signed_at ?? null };
}
