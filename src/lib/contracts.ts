// ملاحظة نظامية تحكم هذا الملف كلّه:
// الأتعاب المشروطة بالحصول على التمويل هي التوصيف الاقتصادي للوساطة
// التمويلية، لا للاستشارة — وقد أفردت ساما لنشاط «الوساطة الرقمية لجهات
// التمويل» ترخيصاً مستقلاً منذ ٢٢ مايو ٢٠٢٣. ومُرضي مرخّصة للاستشارات
// المالية لغير الأوراق المالية، لا للوساطة. فالأتعاب هنا مقابلُ عملٍ
// يُسلَّم، لا مقابلَ نتيجةٍ تتحقّق. ومسار النسبة أُبقي في النوع لأن عقوداً
// قديمة تُقرأ به، ويُقسر إلى الثابت في عقود التمويل — انظر feeClause.
export type FeeType = 'fixed' | 'staged' | 'deferred' | 'percent' | 'both';
export type SuccessBase = 'financing' | 'deal' | 'saving' | 'round';

export interface ContractFields {
  clientName?: string;
  clientIdNumber?: string;
  establishmentName?: string;
  establishmentCr?: string;
  feePercent?: string | number;
  // آلية الأتعاب — يحددها المستشار لكل عقد على حدة
  feeType?: FeeType;            // ثابت · نسبة نجاح · الاثنان معاً
  fixedAmount?: string | number; // المبلغ الثابت بالريال
  successMin?: string | number;  // الحد الأدنى لأتعاب النجاح (مسارات غير التمويل)
  stageOne?: string | number;    // الدفعة الأولى — عند التوقيع
  stageTwo?: string | number;    // الدفعة الثانية — عند تسليم التقرير الختامي
  basisAmount?: string | number; // المبلغ الذي سُعّرت الاتعاب بالرجوع اليه (التسهيل المطلوب)
  basisPercent?: string | number;// النسبة المستعملة في التسعير — مرجعٌ لا استحقاق
  deferDays?: string | number;   // الاجل الاقصى بالايام — تاريخٌ يقين يجعل الدين غير معلق
  floorAmount?: string | number; // ما لا تنزل عنه الاتعاب عند الابراء الجزئي
}

const F = (v: string | number | undefined, fallback: string) =>
  (v === undefined || v === null || v === '') ? fallback : String(v);

const money = (v: string | number | undefined, fallback: string) => {
  const n = Number(v);
  return (v === undefined || v === null || v === '' || !isFinite(n)) ? fallback : Math.round(n).toLocaleString('en-US');
};

/**
 * البند الثاني — الأتعاب. نصٌّ واحد يخدم الآليات الثلاث، فلا يتفرّع العقد ولا يتناقض.
 * قاعدة مقصودة: الرسم الثابت مقابل عملٍ يُنفَّذ سواءً نجحت الصفقة أم لا، فلا يُخصم من نسبة النجاح —
 * وهذا يُذكر صراحةً في العقد لأنه أكثر ما يُتنازع عليه لاحقاً.
 */
export function feeClause(
  f: ContractFields,
  opts: { work: string; baseLabel: string; trigger: string; basisNote?: string; contingentBanned?: boolean }
): string {
  // في عقود التمويل لا يجوز ربط الأتعاب بصرف التمويل مهما اختار المستشار
  // في الشاشة — فالقيد نظامي لا تفضيلي، ومحلُّه الكود لا ذاكرةُ من يملأ النموذج.
  const type: FeeType = opts.contingentBanned
    ? (f.feeType === 'staged' || f.feeType === 'deferred' ? f.feeType : 'fixed')
    : (f.feeType || 'percent');
  const pct = 'نسبة (' + F(f.feePercent, '....') + '٪) من ' + opts.baseLabel;
  // نواة النص بلا ذكر العمل — يُضاف وصف العمل حيث يلزم فقط، فلا يتكرر في جملة واحدة
  const fixedCore = 'مبلغاً ثابتاً قدره (' + money(f.fixedAmount, '..........') + ') ريال سعودي، يُستحق عند توقيع هذا العقد، ولا يُرد؛ إذ يقابل عملاً يُنفَّذ سواءً تمّت الصفقة أم لم تتم';
  const fixedWithWork = 'مبلغاً ثابتاً قدره (' + money(f.fixedAmount, '..........') + ') ريال سعودي، يُستحق عند توقيع هذا العقد مقابل ' + opts.work + '، ولا يُرد؛ إذ يقابل عملاً يُنفَّذ سواءً تمّت الصفقة أم لم تتم';
  const minNote = (f.successMin !== undefined && f.successMin !== null && f.successMin !== '' && Number(f.successMin) > 0)
    ? ' على ألا تقل أتعاب النجاح عن (' + money(f.successMin, '..........') + ') ريال سعودي.'
    : '';
  // أساس الاحتساب: المعتمد أم المسحوب. وتركُه مسكوتاً عنه خصومةٌ مؤجّلة —
  // فسقفٌ بخمسة ملايين يُسحب منه مليونان يجعل الفرق في الأتعاب مئات الآلاف،
  // ولا نصّ يُحتكم إليه. فيُذكر صراحةً حيث يكون للتمويل سقفٌ ودفعات.
  const basis = opts.basisNote ? '\n' + opts.basisNote : '';

  // ★ الأتعاب المؤجّلة (١٩ سبتمبر، معدَّلة) — قرار المالك: مقدَّمٌ عند
  //   التوقيع، ونسبةٌ تُسدَّد عند صرف التمويل، بلا حدٍّ أدنى. وهذا ما يقبله
  //   السوق ولا يقبل غيره.
  //
  //   وحيث إن الأجل مربوطٌ بالصرف، فالغطاء الوحيد الصادق هو **توصيف الخدمة
  //   توصيفاً يطابق الواقع**: الخدمة لا تنتهي بتسليم الملف — تمتدّ إلى
  //   قراءة عرض الجهة وشروطه، ومراجعة اتفاقية التسهيل قبل التوقيع، وترتيب
  //   جدول السحب، ومتابعة استيفاء شروط الصرف. وهذا عملٌ حقيقي ينتهي يوم
  //   يصل المال — فكان حلولُ الأجل يومَه موافقاً لطبيعة الخدمة لا حيلةً
  //   عليها. ويقابله في العقد: نفيٌ صريح لكل صفةٍ وسيطة، وأن أتعابنا من
  //   العميل وحده ولا ريال من جهة ممولة، وأن التقديم والتعاقد بينه وبينها.
  if (type === 'deferred') {
    const up = money(f.stageOne, '..........');
    const pct = F(f.basisPercent, '....');
    return 'يلتزم الطرف الثاني بسداد أتعاب للطرف الأول مقابل ' + opts.work + ' على النحو الآتي:\n'
      + 'أولاً — المقدَّم. مبلغ (' + up + ') ريال سعودي يُسدَّد عند توقيع هذا العقد مقابل فتح الملف '
      + 'ودراسة الحالة وبدء التجهيز، ولا يُرد؛ إذ يقابل عملاً يُنفَّذ بمجرّد البدء.\n'
      + 'ثانياً — أتعاب استكمال الخدمة. نسبة (' + pct + '٪) من قيمة التسهيل الذي يُعتمد للطرف الثاني.\n'
      + 'ثالثاً — ما تقابله هذه الأتعاب. تمتدّ خدمة الطرف الأول إلى ما بعد تسليم الملف، فتشمل: '
      + 'قراءة ما يرد من الجهات وشروطه وبيان أثره بالريال · ومراجعة اتفاقية التسهيل وملاحقها قبل توقيعها · '
      + 'وترتيب جدول السحب بما يوافق دورة العميل النقدية · ومتابعة استيفاء شروط الصرف حتى يتم. '
      + 'وهي خدمةٌ تنتهي بصرف التسهيل، فكان أجل أتعابها يومَه.\n'
      + 'رابعاً — حلول الأجل. تُسدَّد أتعاب استكمال الخدمة عند قيد مبلغ التسهيل في حساب الطرف الثاني '
      + 'أو إتاحته له للسحب. فإن كان التسهيل سقفاً يُسحب منه على دفعات، سُدِّدت مع كل دفعة وبنسبتها، '
      + 'فلا يُطالَب الطرف الثاني بأتعاب عن مبلغ لم يُتَح له.\n'
      + 'خامساً — تُحتسب النسبة على المبلغ المعتمد من جهة التمويل، وتُضاف عليها ضريبة القيمة المضافة '
      + 'بحسب النظام، ويصدر بها فاتورة ضريبية نظامية.\n'
      + 'سادساً — لا يتقاضى الطرف الأول أي عمولة أو مقابل — مباشر أو غير مباشر — من أي جهة تمويل، '
      + 'وأتعابه من الطرف الثاني وحده مقابل خدمةٍ استشارية يؤدّيها له. '
      + 'ولا يضمن الطرف الأول موافقة أي جهة، ولا يمنح تمويلاً ولا يعتمده، '
      + 'ويبقى التقديم والتعاقد بين الطرف الثاني والجهة مباشرةً.';
  }
  if (type === 'staged') {
    const s1 = money(f.stageOne, '..........');
    const s2 = money(f.stageTwo, '..........');
    const total = money(f.fixedAmount, '..........');
    // التسعير بالرجوع إلى حجم التسهيل المطلوب ممارسةٌ استشارية معتادة: العمل
    // يكبر بكبر الملف. والفرق الحاسم ان الأتعاب تُستحق بالتسليم لا بالنتيجة —
    // ولذلك تُذكر النسبة بوصفها «اساس تسعير» لا بوصفها استحقاقاً على تمويل.
    const basis = (f.basisAmount !== undefined && f.basisAmount !== null && String(f.basisAmount) !== ''
      && f.basisPercent !== undefined && f.basisPercent !== null && String(f.basisPercent) !== '')
      ? 'وقد حُدِّد هذا المبلغ بالرجوع إلى حجم الملف محل الخدمة، بواقع ('
        + F(f.basisPercent, '....') + '٪) من قيمة التسهيل المطلوب البالغة ('
        + money(f.basisAmount, '..........') + ') ريال سعودي. '
        + 'وهذه النسبة أساسُ تسعيرٍ لقياس حجم العمل لا غير، ولا تُعد استحقاقاً على تمويل، '
        + 'ولا يتغيّر المبلغ بارتفاع ما يحصل عليه الطرف الثاني أو انخفاضه أو بعدم حصوله عليه أصلاً.\n'
      : '';
    const defer = (f.deferDays !== undefined && f.deferDays !== null && String(f.deferDays) !== '' && Number(f.deferDays) > 0)
      ? 'وللطرف الثاني أن يطلب كتابةً تأجيل سداد الدفعة الثانية إلى تاريخٍ لا يتجاوز ('
        + F(f.deferDays, '....') + ') يوماً من تاريخ توقيع هذا العقد، فيُجاب إلى ذلك. '
        + 'وهذا تأجيلٌ في موعد السداد لا تعليقٌ للاستحقاق: تبقى الأتعاب مستحقةً في ذمته '
        + 'كاملةً وفي ذلك التاريخ، سواءً حصل على تمويل أم لم يحصل.\n'
      : '';
    return 'يلتزم الطرف الثاني بسداد أتعاب للطرف الأول مقابل ' + opts.work + ' قدرها ('
      + total + ') ريال سعودي.\n'
      + basis
      + 'وتُسدَّد على دفعتين:\n'
      + '(أ) مبلغ (' + s1 + ') ريال عند توقيع هذا العقد وبدء العمل.\n'
      + '(ب) مبلغ (' + s2 + ') ريال عند تسليم التقرير الختامي للخدمة، متضمناً الملف الائتماني '
      + 'المكتمل وسجل الجهات التي عُرض عليها وردودها وما طلبته.\n'
      + defer
      + 'وكلتا الدفعتين مقابل عملٍ يُنفَّذ ويُسلَّم، وتُستحق بتسليمه، ولا ترتبط بحصول '
      + 'الطرف الثاني على تمويل ولا بمقداره ولا بموافقة أي جهة ولا برفضها.\n'
      + 'ولا يستحق الطرف الأول أي نسبة من قيمة التمويل ولا أي أتعاب نجاح في هذا العقد، '
      + 'ولا يتقاضى أي عمولة أو مقابل — مباشر أو غير مباشر — من أي جهة تمويل.';
  }

  if (type === 'fixed') {
    return 'يلتزم الطرف الثاني بسداد أتعاب للطرف الأول مقابل ' + opts.work + ' ' + fixedCore + '.\n'
      + 'وهذه الأتعاب مقابلُ العمل المُسلَّم، ولا ترتبط بحصول الطرف الثاني على تمويل ولا بمقداره '
      + 'ولا بموافقة أي جهة.\n'
      + 'ولا يستحق الطرف الأول أي نسبة من قيمة التمويل ولا أي أتعاب نجاح في هذا العقد، '
      + 'ولا يتقاضى أي عمولة أو مقابل — مباشر أو غير مباشر — من أي جهة تمويل.';
  }
  if (type === 'both') {
    return 'يلتزم الطرف الثاني بسداد أتعاب للطرف الأول على شقّين:\n'
      + '(أ) ' + fixedWithWork + '.\n'
      + '(ب) أتعاب نجاح قدرها ' + pct + '، وتستحق عند ' + opts.trigger + '.' + minNote + basis + '\n'
      + 'والشقّان مستقلان: لا يُخصم المبلغ الثابت من أتعاب النجاح، لاختلاف ما يقابله كلٌّ منهما.';
  }
  return 'يلتزم الطرف الثاني بسداد أتعاب للطرف الأول مقابل ' + opts.work + ' قدرها ' + pct + '.' + minNote + '\n'
    + 'وتستحق هذه الأتعاب عند ' + opts.trigger + '.' + basis + '\n'
    + 'ولا يستحق الطرف الأول أي مبلغ مقدّم في هذا العقد.';
}

