export function findTemplate(key: string): Template | null {
  return TEMPLATES.find((t) => t.key === key) || null;
}

// يملأ المتغيّرات. وإن غاب متغيّر، حُذف السطر الذي يحمله كاملاً بدل أن
// تخرج رسالة فيها «{{company}}» إلى عميل — إلا سطر النداء، فله بديل محايد.
const DROP = '\u0000';

export function fillTemplate(
  text: string,
  vars: { name?: string; company?: string; sender?: string }
): string {
  const map: Record<string, string> = {
    name: (vars.name || '').trim(),
    company: (vars.company || '').trim(),
    sender: (vars.sender || '').trim(),
  };
  const filled = text
    // نداء بلا اسم يصير تحيّة، لا سطراً محذوفاً
    .replace(
      /^أستاذ \{\{name\}\}،$/m,
      map.name ? 'أستاذ ' + map.name + '،' : 'السلام عليكم ورحمة الله،'
    )
    .replace(/\{\{(name|company|sender)\}\}/g, (_m, k: string) => map[k] || DROP);

  return filled
    .split('\n')
    .filter((line) => !line.includes(DROP))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}
