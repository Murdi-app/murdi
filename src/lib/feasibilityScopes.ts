// بوابة نطاقات البحث لدراسة الجدوى وحدها — لا يستوردها مسار التمويل ولا الاستثمار
// المبدأ: يُفتح باب عائلة الممولين حين يملك المشروع الخاصية التي تموّلها تلك العائلة،
// لا حين يبلغ حجماً معيناً. فبنك التصدير الكوري لا يموّل الحجم، يموّل صادرات كورية.
// والشرط الثاني هو الحجم: فحتى مع وجود الخاصية، بعض العائلات تذاكرها أكبر من الطلب.

export type PropertyMode = 'rent' | 'buy' | 'own';
export type CapexKind = 'equipment' | 'property' | 'vehicles' | 'fitout' | 'tech' | 'inventory' | 'mixed';

export interface FzMatchProfile {
  ask: number;                 // التمويل المطلوب بالريال
  totalInvestment: number;
  isNew: boolean;              // مشروع جديد أم توسعة نشاط قائم
  imports: boolean;            // يستورد معدات أو بضائع من الخارج
  importCountries: string;     // نص حر: الدول المورّدة
  property: PropertyMode;      // إيجار · شراء عقار · عقار مملوك
  capexKind: CapexKind;        // أكبر بند في التكلفة الرأسمالية
  foreignOwner: boolean;
  ownerNationality: string;
  largeBuyers: boolean;        // عملاؤه شركات كبرى معروفة بالاسم
  sectorText: string;
}

const M = 1_000_000;

export function buildFeasibilityScopes(p: FzMatchProfile): string[] {
  const s: string[] = [];
  const ask = Math.max(0, p.ask);
  const countries = p.importCountries.trim();

  // ═══ دائماً: الأبواب التي لا تشترط خاصية ═══
  s.push('اقتصر على البنوك السعودية المرخّصة من البنك المركزي السعودي وبرامجها لتمويل المنشآت الصغيرة والمتوسطة، وبيّن لكل بنك حده الأدنى والأعلى وشروط الضمان.');
  s.push('اقتصر على شركات التمويل المرخّصة من البنك المركزي السعودي التي تموّل المنشآت الصغيرة والمتوسطة — لا بنوك.');
  if (!p.foreignOwner) {
    s.push('اقتصر على برامج الضمان الحكومية وضمانات كفالة والجهات التي تسهّل وصول المنشآت الصغيرة للتمويل البنكي، وبيّن نسبة التغطية وشروط الأهلية.');
  }

  // ═══ الحجم الصغير: أبواب لا تُفتح لطلب كبير ═══
  // ولا تُفتح لمملوك أجنبي: البرامج الحكومية والضمانات لها شروط ملكية،
  // ووعدٌ واحد بها بلا تحقق مكتوب يحرق السمعة في مجتمع يتحدث مع بعضه
  if (ask <= 5 * M && !p.foreignOwner) {
    s.push('اقتصر على بنك التنمية الاجتماعية وبرامجه التمويلية للمنشآت والأسر المنتجة في السعودية.');
    s.push('اقتصر على منشآت وبرامجها التمويلية والداعمة للمنشآت الصغيرة والمتناهية الصغر وبرامج الجهات الحكومية المشابهة.');
    s.push('اقتصر على منصات التمويل الجماعي بالدين المرخّصة من البنك المركزي السعودي.');
  }

  // ═══ خاصية: يشتري معدات أو مركبات ═══
  if (p.capexKind === 'equipment' || p.capexKind === 'vehicles' || p.capexKind === 'mixed' || p.capexKind === 'tech') {
    s.push('اقتصر على شركات الإجارة وتمويل المعدات والأصول في السعودية: إجارة منتهية بالتمليك لمعدات التشغيل والتجهيزات، وبرامج تمويل الأصول لدى البنوك وشركات التمويل المرخّصة.');
  }
  if (p.capexKind === 'vehicles') {
    s.push('اقتصر على شركات تمويل وتأجير المركبات وإدارة الأساطيل العاملة في السعودية.');
  }
  if ((p.capexKind === 'equipment' || p.capexKind === 'vehicles') && ask >= 2 * M) {
    s.push('اقتصر على أذرعة التمويل التابعة لمصنّعي المعدات (Vendor وCaptive Finance) التي تموّل المشترين في السعودية والخليج.');
  }

  // ═══ خاصية: عقار — لا تُفتح لمستأجر ═══
  if (p.property === 'buy') {
    s.push('اقتصر على شركات التمويل العقاري التجاري المرخّصة من البنك المركزي السعودي التي تموّل شراء موقع أو مبنى لنشاط تجاري بضمان العقار نفسه.');
  }
  if (p.property === 'own') {
    s.push('اقتصر على التمويل المضمون بأصل عقاري مملوك: الرهن التجاري وبرامج البيع وإعادة الاستئجار (Sale and Leaseback) في السعودية.');
  }

  // ═══ خاصية: يستورد ═══
  if (p.imports) {
    s.push('اقتصر على مزوّدي تمويل التجارة والاعتمادات المستندية وخطابات الضمان للمنشآت السعودية من البنوك العاملة في المملكة.');
    if (ask >= 500_000) {
      s.push('اقتصر على منصات تمويل الفواتير والتجارة العابرة للحدود: Incomlend وStenn وDrip Capital وModifi وVelotrade وما شابهها، وبيّن شروط قبولها للمستورد السعودي.');
    }
    // وكالات ائتمان التصدير وبنوك المشتري: باب دولة المورّد تحديداً، وبتذكرة لا تقل عن مليونين
    if (ask >= 2 * M && countries) {
      s.push('اقتصر على وكالات ائتمان التصدير وبنوك تمويل المشتري في هذه الدول تحديداً: ' + countries
        + '. وضّح لكل جهة شرط أن يبدأ الملف من المورّد، والحد الأدنى للصفقة، وحاجة الترتيب إلى بنك سعودي وسيط.');
    }
  }

  // ═══ خاصية: مالك أجنبي — آلية الممر المعتمدة ═══
  if (p.foreignOwner && p.ownerNationality.trim()) {
    s.push('اقتصر على بنوك ' + p.ownerNationality.trim() + ' ومؤسساتها التمويلية وفروعها ومكاتبها في الخليج التي تخدم الشركات المملوكة لمواطنيها العاملة في السعودية.');
    s.push('اقتصر على الجهات التي تقبل ضمان الشركة الأم الأجنبية (Parent Company Guarantee) لتمويل ذراعها السعودي، وبيّن شكل الضمان المطلوب.');
  }
  if (p.foreignOwner || p.imports || ask >= 5 * M) {
    s.push('اقتصر على البنوك الأجنبية والخليجية التي لها فروع مرخّصة من البنك المركزي السعودي وتعمل داخل المملكة، وبيّن حدودها الدنيا للمنشآت.');
  }

  // ═══ خاصية: عملاء كبار — تمويل الذمم وسلاسل الإمداد ═══
  if (p.largeBuyers && ask >= M) {
    s.push('اقتصر على برامج تمويل سلاسل الإمداد وخصم الفواتير (Supply Chain Finance) التي تموّل موردي الشركات الكبرى في السعودية.');
  } else if (!p.isNew) {
    s.push('اقتصر على تمويل الموردين والدفع الآجل بين الشركات والمنصات التي تموّل المشتريات التشغيلية للمنشآت السعودية.');
  }

  // ═══ الحجم الكبير وحده ═══
  if (ask >= 5 * M && (p.imports || p.foreignOwner)) {
    s.push('اقتصر على المؤسسات التنموية ومتعددة الأطراف التي تموّل التجارة والمشاريع في السعودية: ITFC وICD وIsDB وأبيكورب وIFC.');
  }
  if (ask >= 20 * M) {
    s.push('اقتصر على صناديق الدين الخاص والإقراض المباشر ذات التفويض المعلن في الشرق الأوسط، وبيّن حدها الأدنى للصفقة.');
    s.push('اقتصر على مرتّبي الصكوك والطرح الخاص وأدوات الدين للمنشآت المتوسطة في السعودية والخليج.');
  }

  return s;
}

// وصف البوابة بالعربية — يُعرض للمستخدم ويُحفظ في تشخيص التشغيلة
export function describeGate(p: FzMatchProfile, n: number): string {
  const on: string[] = [];
  if (p.ask <= 5_000_000) on.push('حجم صغير');
  if (p.capexKind === 'equipment' || p.capexKind === 'vehicles' || p.capexKind === 'mixed' || p.capexKind === 'tech') on.push('تمويل معدات');
  if (p.property === 'buy') on.push('شراء عقار');
  if (p.property === 'own') on.push('عقار مملوك');
  if (p.imports) on.push('استيراد' + (p.importCountries.trim() ? ' من ' + p.importCountries.trim() : ''));
  if (p.foreignOwner) on.push('ممر مالك أجنبي' + (p.ownerNationality.trim() ? ' — ' + p.ownerNationality.trim() : ''));
  if (p.largeBuyers) on.push('عملاء كبار');
  if (p.ask >= 20_000_000) on.push('طلب كبير');
  return n + ' نطاقاً — ' + (on.length ? 'فُتحت لـ: ' + on.join(' · ') : 'الأبواب الأساسية فقط');
}
