// ما تراه كل موظفة — معرَّفاً مرةً واحدة.
//
// ★ كان التعريف في مكانين: قائمةٌ بيضاء في `layout` وعلامةُ `staff` في
//   `AdminNav`. وكلاهما يعرف «موظفة» ولا يعرف **أيّ موظفة**، فرأت المتابِعةُ
//   خمسة تبويبات أربعةٌ منها ليست عملها، ورأت المساعدةُ تبويب المتابعة وهي
//   لا تتابع. والتشتيت وحده يكفي سبباً — فما بالك بأن تفتح شاشةً تفعل فيها
//   ما ليس لها.
//
// ★ فصار الباب واحداً: هذا الملف. من أراد فتح صفحة لموظفة يفتحها هنا، فتُفتح
//   في الشريط وفي الحارس معاً — ولا يُفتح أحدهما وينسى الآخر.
//
// ★ والقائمة بيضاء عمداً: أي صفحة إدارة جديدة مغلقة على الموظفات حتى تُذكر.

// ═══════════════════════════════════════════════════════════════════════
// ⚑⚑ القسمة بين الموظفتين — قسمةُ **مرحلة** لا قسمةُ أداة (المالك، ٢٧ سبتمبر)
//
//   · **ضي** — أوّل الرحلة: من لحظة وصول العميل إلى المنصة **حتى يدفع**.
//     الوارد، ومكالمة من طرق بابنا، والفرص الساخنة، ومكتب الطلبات، والتسعير،
//     وتأكيد التحويل، ومراسلة العملاء. فكلُّ عميلٍ **لم يدفع** فهو لها.
//   · **رغد** — ما بعد الدفع: **العميل الذي دفع**، وجهاتُ التمويل. جمع
//     مستنداته ومتابعته حتى يُغلق ملفه، والاتصال بالجهات وجمع أسماء
//     مسؤوليها وأرقامهم. فكلُّ عميلٍ **دفع** فهو لها.
//
// ★ وكانت الشاشات موزَّعةً بالمقلوب حتى هذا اليوم: `assistant` (رغد) تملك
//   صفَّ ما قبل الدفع كلَّه — الوارد والمكالمات والفرص الساخنة والمراسلة —
//   و`followup` (ضي) لا ترى «الفرص الساخنة» وهي أحرُّ شاشةٍ في عملها، وترى
//   «المتابعة» وهي مخاطبةُ جهاتٍ ليست من عملها أصلاً. فصُحّحت هنا.
//
// ⚠️ **والرمزان أدناه رمزان تاريخيان ولا يُقرأ منهما معناهما اللغوي:**
//     `followup` = **ضي** = ما قبل الدفع ·  `assistant` = **رغد** = ما بعده.
//     وصفُّ `staff.job` في القاعدة مطابقٌ لذلك (ضي=followup · رغد=assistant).
//     **وهذا الملف هو المرجع، لا اسم الرمز.**
// ═══════════════════════════════════════════════════════════════════════

export type StaffJob = 'assistant' | 'followup';

/** اسم المرحلة التي يعمل فيها الدور — يُعرض ويُكتب في الرسائل */
export const STAGE_OF: Record<StaffJob, string> = {
  followup: 'من الباب إلى الدفع',
  assistant: 'ما بعد الدفع وجهات التمويل',
};

/** صفحات كل دور، بترتيب ظهورها — وأولها شاشته الأولى */
export const PAGES_BY_JOB: Record<StaffJob, { href: string; label: string; icon: string }[]> = {
  // ═══ ضي — من الباب إلى الدفع ═══
  //
  // ★ «الوارد» (٢٤ سبتمبر) شاشتها الأولى. والسبب عطبٌ قائم منذ فُتحت حملة
  //   الإعلان: الأبواب التي يدخل منها الناس ستة، وكانت موزَّعةً على شاشاتٍ
  //   ليست كلّها لها. طلبُ الخدمة من الموقع — وهو أحرّ ما يصل، صاحبه كتب
  //   اسمه وجواله وسمّى الخدمة — يُعرض في «الفرص الساخنة» وحدها، ولم تكن في
  //   قائمتها. فمرّ علاء جميل سراج وخالد الشهري وعبدالله المحيميد ولم ترَ
  //   منهم اسماً. وما تراه («مكالمات اليوم») يرتّب بالتأهّل لا بالوقت،
  //   فالداخل الجديد يسقط إلى ذيل مئة صفّ. فهذه شاشةٌ تقول شيئاً واحداً:
  //   من طرق البابَ، ومتى، ورقمه. أحدثُ أولاً.
  followup: [
    { href: '/admin/arrivals', label: 'الوارد', icon: '📥' },
    { href: '/admin/leads', label: 'مكالمات اليوم', icon: '📋' },
    // ★ أُعيدت إليها (٢٧ سبتمبر): «الفرص الساخنة» تجمع كل من طرق بابنا
    //   مرتَّباً بقربه من الدفع، وهو لبُّ عملها — وكانت في قائمة رغد وحدها.
    { href: '/admin/hot', label: 'الفرص الساخنة', icon: '🔥' },
    // مكتب الطلبات: تعتمد وترفض طلبات الخدمة وطلبات المطابقة، وتؤكّد
    // التحويل، وترى بيانات كل عميل كاملةً لتتصل به. ولم تُفتح لها
    // `/admin/services` ولا `/admin/approvals`: في الأولى أزرار التوليد
    // كلّها، وفي الثانية العقود والتسعير ومحادثة البحث. وإخفاء زرٍّ في
    // المتصفح ليس حماية؛ فالصواب بابٌ لا يمرّ به ما لا يلزم.
    { href: '/admin/desk', label: 'الخدمات والاعتمادات', icon: '📑' },
    { href: '/admin/message', label: 'مراسلة العملاء', icon: '💬' },
  ],

  // ═══ رغد — ما بعد الدفع وجهات التمويل ═══
  //
  // ★ رُفعت من قائمتها (٢٧ سبتمبر) أربعُ شاشاتٍ كلُّها صفُّ ما قبل الدفع:
  //   الوارد · مكالمات اليوم · الفرص الساخنة · مراسلة العملاء. وقد كانت
  //   تزاحم ضي على العميل نفسه، ويبقى العميلُ الذي **دفع** بلا أحد:
  //   خمسة ملفّات مدفوعة وقفت بين ستة أيام وأربعين.
  //
  // ★ و«صيد اليوم» خرج بأمر المالك (١١ سبتمبر): الصيد اتصالٌ بارد بمن لا
  //   يعرفنا، ونسبة تحويله الأدنى في المنصة. والصفحة باقية بالرابط لمن
  //   أرادها، وليست في شريطها.
  assistant: [
    // شاشتها الأولى: أبواب التمويل — من رُدّ عليه ومن تأخّر ومن لم يُعطِ
    // اسماً بعد. وعملها فيها: الاتصال، وجمع اسم مسؤول الائتمان ورقمه المباشر.
    { href: '/admin/followup', label: 'متابعة الجهات', icon: '📞' },
    // ومكتب الطلبات **قراءةً لا قراراً**: منه ترى الملفّات المدفوعة وأرقام
    // أصحابها لتجمع مستنداتها. والقرارُ فيه لضي وحدها — مفروضٌ في الخادم
    // (`/api/staff/desk`) لا في إخفاء زرّ.
    { href: '/admin/desk', label: 'ملفّات العملاء', icon: '📑' },
  ],
};

/**
 * مَن يقرّر في مكتب الطلبات: الاعتماد والرفض وتأكيد التحويل.
 *
 * ★ ضي وحدها — لأن القرار كلَّه واقعٌ على عميلٍ **لم يدفع بعد**، وذاك صفُّها.
 *   ورغد ترى المكتب لتعرف ملفّاتها المدفوعة، ولا تضغط فيه زرّاً.
 *   ويُقرأ هذا في الشاشة وفي الخادم معاً — فلا يُخفى زرٌّ ويبقى مساره مفتوحاً.
 */
export const decidesAtDesk = (job: StaffJob): boolean => job === 'followup';

/** أول صفحة يُردّ إليها صاحب الدور */
export const homeFor = (job: StaffJob): string =>
  PAGES_BY_JOB[job]?.[0]?.href || '/admin/followup';

/** هل يُسمح لصاحب هذا الدور بهذا المسار؟ */
export const mayVisit = (job: StaffJob, pathname: string): boolean =>
  (PAGES_BY_JOB[job] || []).some((p) => String(pathname || '').startsWith(p.href));

const JOBS: StaffJob[] = ['assistant', 'followup'];
export const asJob = (v: unknown): StaffJob =>
  JOBS.find((j: StaffJob) => j === String(v ?? '')) || 'assistant';
