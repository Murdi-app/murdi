export const isAskKind = (k: unknown): k is AskKind => k === 'new' || k === 'expand' || k === 'working';

/** نوع الطلب من سطر ملخّصه («⭐ … فكرة أو مشروع جديد · …») */
export function kindFromNote(note: string | null | undefined): AskKind {
  const n = String(note || '');
  if (/منشأة قائمة تحتاج سيولة/.test(n)) return 'working';
  if (/توسعة/.test(n)) return 'expand';
  return 'new';
}
