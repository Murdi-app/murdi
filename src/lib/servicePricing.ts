// السعر النهائي لخدمة، مع مراعاة التدرّج بحجم الاستثمار حين ينطبق
export function priceFor(title: string, investment?: number): { amount: number | null; label: string } {
  const c = COMMERCIAL[title];
  if (!c) return { amount: null, label: 'بعرض خاص' };
  if (c.tiersBy === 'investment' && c.tiers) {
    if (!investment || investment <= 0) {
      const first = c.tiers[0];
      return { amount: null, label: 'من ' + first.price.toLocaleString('en-US') + ' ريال — أدخل حجم استثمارك ليظهر سعرك' };
    }
    for (const t of c.tiers) {
      if (t.upTo === null || investment <= t.upTo) {
        return t.price > 0
          ? { amount: t.price, label: t.price.toLocaleString('en-US') + ' ريال' }
          : { amount: null, label: 'بعرض خاص' };
      }
    }
  }
  if (c.price === null || c.price === undefined) return { amount: null, label: 'بعرض خاص' };
  return { amount: c.price, label: c.price.toLocaleString('en-US') + ' ريال' };
}
